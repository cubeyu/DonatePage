// 构建脚本：打包压缩 JS/CSS 到 assets/bundles/，并将完整站点产出至 public/ 供部署
// 安全约束：所有任务均不修改源文件（index.html 只读，压缩结果只写入 public/）
const fs = require('fs');
const gulp = require('gulp');
const { Transform } = require('stream');
const cleanCSS = require('gulp-clean-css');
const concat = require('gulp-concat');
const htmlmin = require('gulp-htmlmin');
const terser = require('gulp-terser');

// 裁剪 iconfont sprite：上游 iconfont.js 携带已删渠道（paypal/tenpay）的死图标 symbol，
// terser 不会删字符串内容，故在打包时按页面实际引用（index.html 的 <use>）白名单过滤。
// 源文件保持上游原样不动。
const ICONS_USED = ['icon-weixinzhifu', 'icon-iconfontrectangle390'];
function stripUnusedIcons() {
  const anySymbol = /<symbol id="([^"]+)"[^>]*>[\s\S]*?<\/symbol>/g;
  return new Transform({
    objectMode: true,
    transform(file, encoding, cb) {
      if (!file.isNull() && !file.isStream() && /iconfont\.js$/.test(file.path)) {
        file.contents = Buffer.from(String(file.contents).replace(anySymbol, function (m, id) {
          return ICONS_USED.indexOf(id) !== -1 ? m : '';
        }));
      }
      cb(null, file);
    },
  });
}

// 清理上一次的构建产物，避免旧文件残留
gulp.task('clean', function (done) {
  fs.rmSync('./public', { recursive: true, force: true });
  done();
});

// 合并压缩 JS：图标库 + jQuery + 二维码库 + 页面逻辑 → assets/bundles/function.main.js
gulp.task('pack-js', function () {
  return gulp.src([
      './assets/js/iconfont.js',
      './node_modules/jquery/dist/jquery.js',
      './assets/js/jquery-qrcode.js',
      './assets/js/function.js'
  ])
  .pipe(stripUnusedIcons())
  .pipe(concat('function.main.js'))
  .pipe(terser())
  .pipe(gulp.dest('./assets/bundles/'));
});

// 合并压缩 CSS：蓝图风格自包含样式 → assets/bundles/style.main.css
// （spectre 框架已移除，样式全部在 style.css 内自包含）
gulp.task('pack-css', function () {
  return gulp.src([
      './assets/styles/style.css'
  ])
  .pipe(concat('style.main.css'))
  .pipe(cleanCSS({
    level: 2
  }))
  .pipe(gulp.dest('./assets/bundles/'));
});

// 压缩 HTML 并输出到 public/（注意：绝不写回项目根目录，源 index.html 保持可读可维护）
gulp.task('minify-html', function () {
  return gulp.src(['./index.html'], { base: './' })
    .pipe(htmlmin({
      collapseWhitespace: true,
      conservativeCollapse: true,
      collapseInlineTagWhitespace: true,
      collapseBooleanAttributes: true,
      removeComments: true,
      minifyCSS: true,
      minifyJS: true,
      removeRedundantAttributes: true,
      removeScriptTypeAttributes: true,
      removeStyleLinkTypeAttributes: true,
      useShortDoctype: true,
      sortAttributes: true,
      sortClassName: true,
      includeAutoGeneratedTags: false,
    }))
    .pipe(gulp.dest('./public/'));
});

// 复制运行时所需的静态资源（打包产物与图片）到 public/
// 只复制 bundles 与 images，不携带 js/styles 源文件
// encoding: false 让 vinyl 以 Buffer 原样传输二进制（webp/图片），
// 否则 gulp 5 默认按 utf8 解码文本，会把 webp 重新编码导致体积膨胀
gulp.task('copy-assets', function () {
  return gulp.src([
      './assets/bundles/**/*',
      './assets/images/**/*'
    ], { base: './', encoding: false })
    .pipe(gulp.dest('./public/'));
});

gulp.task('build', gulp.series(
  'clean',
  gulp.parallel('pack-js', 'pack-css'),
  gulp.parallel('minify-html', 'copy-assets')
));

gulp.task('default', gulp.series('build'));
